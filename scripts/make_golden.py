#!/usr/bin/env python3
"""Generate shared/golden/pharmacology.json from backend/pharmacology.py (BUILD.md §6.4, §7.4).

PROTECTED OUTPUT (BUILD.md §0.7): shared/golden/pharmacology.json was generated ONCE by this script
and is read-only from then on. Do not re-run it to make a failing test pass; fix the implementation
instead. The script refuses to overwrite an existing golden file unless --force is given, and a forced
regeneration must produce identical numbers (it is only for re-creating a deleted file).

Cases (all T = 25 min, dt = 1/600 min, sampled every 0.1 min = every 60th point):
  * each dose step at sensitivity 1, clearance 1;
  * three variability cases at the strong dose: (sensitivity, clearance) = (1.3, 1.0), (0.75, 1.0), (1.0, 1.4);
  * one repeat-hit case: strong dose, hits at 6.0 and 8.0 min (strong dose each); the second request
    lands while visual >= 3 and is deferred until visual < 3.
Usage: uv run python scripts/make_golden.py [--force]
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from backend.pharmacology import DOSES, HIT_BLOCK_VISUAL, P, simulate  # noqa: E402

OUT = ROOT / "shared" / "golden" / "pharmacology.json"
T, DT, EVERY = 25.0, 1 / 600, 60
VARIABILITY = [(1.3, 1.0), (0.75, 1.0), (1.0, 1.4)]
REPEAT_HITS = [(6.0, DOSES["strong"]), (8.0, DOSES["strong"])]


def applied_hit_times(ts, I, hits):
    """Times at which simulate() applied each requested hit (same rule as the reference loop)."""
    out, pending = [], sorted(hits)
    for i, t in enumerate(ts):
        if pending and t >= pending[0][0] and I[1, i] < HIT_BLOCK_VISUAL:
            out.append({"requested_t": pending[0][0], "dose": pending[0][1], "applied_t": float(t), "index": i})
            pending.pop(0)
    return out


def case(name, dose, sensitivity=1.0, clearance=1.0, hits=()):
    ts, C, I = simulate(dose, sensitivity, clearance, T=T, dt=DT, hits=hits)
    sl = slice(0, None, EVERY)
    c = {"name": name, "dose": dose, "sensitivity": sensitivity, "clearance": clearance,
         "hits": [[t, d] for t, d in hits],
         "t": [round(float(x), 10) for x in ts[sl]],
         "plasma": [round(float(x), 10) for x in C[sl]],
         "body": [round(float(x), 10) for x in I[0, sl]],
         "visual": [round(float(x), 10) for x in I[1, sl]],
         "auditory": [round(float(x), 10) for x in I[2, sl]]}
    if hits:
        c["hits_applied"] = applied_hit_times(ts, I, hits)
    return c


def build():
    cases = [case(step, d) for step, d in DOSES.items()]
    cases += [case(f"strong_s{s}_c{c}", DOSES["strong"], s, c) for s, c in VARIABILITY]
    cases.append(case("strong_repeat_hits", DOSES["strong"], hits=REPEAT_HITS))
    meta = {"source": "backend/pharmacology.py (BUILD.md section 7.4), generated by scripts/make_golden.py",
            "protected": True,
            "params": {k: (list(v) if isinstance(v, tuple) else v) for k, v in P.items()},
            "doses": dict(DOSES),
            "units": "concentrations relative to the half-effect level; intensities 0-10; time in minutes",
            "T": T, "dt": DT, "sample_every_steps": EVERY, "sample_interval_min": EVERY * DT,
            "n_samples": len(cases[0]["t"]), "hit_block_visual": HIT_BLOCK_VISUAL,
            "fields": ["t", "plasma", "body", "visual", "auditory"], "tolerance": 1e-3}
    return {"meta": meta, "cases": cases}


def main():
    data = build()
    if OUT.exists() and "--force" not in sys.argv:
        old = json.loads(OUT.read_text())
        same = json.dumps(old, sort_keys=True) == json.dumps(json.loads(json.dumps(data)), sort_keys=True)
        print(f"{OUT} exists and is protected; regenerated content identical: {same}. Not overwritten.")
        return 0 if same else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(data, separators=(",", ":")) + "\n")
    print(f"wrote {OUT} ({len(data['cases'])} cases, {data['meta']['n_samples']} samples each)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
